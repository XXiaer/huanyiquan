CREATE TABLE IF NOT EXISTS item_conversation (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 item_id BIGINT NOT NULL, seller_id BIGINT NOT NULL, buyer_id BIGINT NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY item_buyer (item_id,buyer_id), KEY chat_seller (seller_id,id), KEY chat_buyer (buyer_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS private_message (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 conversation_id BIGINT NOT NULL, sender_id BIGINT NOT NULL,
 kind VARCHAR(10) NOT NULL, content VARCHAR(1000) NOT NULL DEFAULT '', image VARCHAR(500) NOT NULL DEFAULT '',
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY conversation_messages (conversation_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ring_message (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 exchange_id BIGINT NOT NULL, sender_id BIGINT NOT NULL,
 content VARCHAR(500) NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY ring_messages (exchange_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS wish_post (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT NOT NULL, title VARCHAR(100) NOT NULL, content VARCHAR(500) NOT NULL DEFAULT '',
 category VARCHAR(20) NOT NULL DEFAULT '', status TINYINT NOT NULL DEFAULT 1,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY wish_status_recent (status,id), KEY wish_user (user_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS ring_match_notice (
 ring_key VARCHAR(100) NOT NULL PRIMARY KEY,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
